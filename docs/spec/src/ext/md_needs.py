"""Render the specs for the Markdown builder, and fix up links for every builder.

For the Markdown builder, each Sphinx-Needs item becomes an anchor at its ID, a
bold heading line, a bullet list of its fields and links, and its body. Table
cells are joined onto one line, and each section's label becomes its anchor.

The sources link to files of the repository outside the spec directory by
relative paths, which work where GitHub shows the sources. Each Markdown file is
one directory up from its source (src/network/x.rst gives network/x.md), so
those links lose one "../". The HTML output links them to GitHub.

Each generated Markdown file starts with a comment that names its source and
says that the file is generated.
"""

import os
import posixpath

from docutils import nodes
from sphinx_needs.data import SphinxNeedsData
from sphinx_needs.nodes import Need

TYPE_TITLE = {
    "expectation": "Expectation",
    "hostreq": "Host requirement",
    "ceiling": "Ceiling",
    "req": "Requirement",
    "principle": "Principle",
    "rationale": "Rationale",
}

FIELDS = [
    ("observed_from", "Observed from"),
    ("depends_on", "Depends on"),
    ("platforms", "Platforms"),
    ("key", "Key"),
    ("when", "When"),
    ("kind", "Kind"),
    ("kernel_options", "Kernel options"),
    ("tags", "Tags"),
    ("seconds", "Seconds"),
    ("source_kind", "Source kind"),
    ("source", "Source"),
]

# (field, outgoing label, incoming label)
LINKS = [
    ("refines", "Refines", "Refined by"),
    ("provisional_on", "Provisional on", "Provisional basis of"),
    ("exact_form_of", "Exact form of", "Exact form"),
    ("cli_for", "CLI form of", "CLI form"),
    ("pins", "Pins", "Pinned by"),
    ("needs", "Needs", "Needed by"),
    ("within", "Within", "Bounds"),
    ("assumes", "Assumes", "Assumed by"),
    ("narrows", "Narrows", "Does not cover"),
    ("concerns", "Concerns", "Concerned by"),
    ("violates", "Violates", "Violated by"),
    ("rationale", "Rationale", "Rationale of"),
]

GITHUB = "https://github.com/moby/moby/blob/master/"
#: The directory of the sources in the repository, which relative links start from.
SRC_PATH = "docs/spec/src"
#: The first line of a generated Markdown file; the path is relative to the directory of the Makefile.
HEADER = '<!-- Generated from src/{docname}.rst by "make md". Do not edit this file: edit the source and run "make md". -->'


#: Links shown with the target's title as well as its ID.
TITLED = {"narrows_back", "rationale"}


def _need_ref(app, fromdocname, needs, need_id, titled=False):
    target = needs.get(need_id)
    if target is None:
        return nodes.literal(text=need_id)
    if titled:
        ref = _need_ref(app, fromdocname, needs, need_id)
        return [nodes.Text(target["title"] + " ("), ref, nodes.Text(")")]
    if target["docname"] == fromdocname:
        uri = "#" + need_id
    else:
        uri = app.builder.get_relative_uri(fromdocname, target["docname"]) + "#" + need_id
    return nodes.reference("", need_id, refuri=uri, internal=True)


def _item(label, children):
    para = nodes.paragraph()
    para += nodes.strong(text=label + ":")
    para += nodes.Text(" ")
    para.extend(children)
    li = nodes.list_item()
    li += para
    return li


def _sorted_ids(ids):
    return sorted(ids)


def unwrap_table_cells(doctree):
    """Join the source's line wrapping inside table cells: a Markdown table cell is one line."""
    for entry in doctree.findall(nodes.entry):
        for text in list(entry.findall(nodes.Text)):
            if "\n" in text:
                text.parent.replace(text, nodes.Text(str(text).replace("\n", " ")))


def rewrite_external_links(app, doctree, fromdocname):
    """Point relative links to files outside the spec directory at the right place."""
    for ref in doctree.findall(nodes.reference):
        uri = ref.get("refuri", "")
        if not uri.startswith("../") or ref.get("internal"):
            continue
        if app.builder.name == "markdown":
            ref["refuri"] = uri[len("../"):]
        else:
            path = posixpath.normpath(posixpath.join(SRC_PATH, posixpath.dirname(fromdocname), uri))
            ref["refuri"] = GITHUB + path


def render(app, doctree, fromdocname):
    rewrite_external_links(app, doctree, fromdocname)
    if app.builder.name != "markdown":
        return
    unwrap_table_cells(doctree)
    needs = SphinxNeedsData(app.env).get_needs_view()
    for node in list(doctree.findall(Need)):
        need_id = node.attributes["ids"][0]
        need = needs[need_id]
        new = nodes.container(classes=["need"])
        new += nodes.target("", "", ids=[need_id])
        head = nodes.paragraph()
        kind = TYPE_TITLE.get(need["type"], need["type"])
        if need["type"] == "expectation":
            kind = f"{kind} ({need.get('category')})"
        head += nodes.strong(text=f"{kind} {need_id}")
        head += nodes.Text(": " + need["title"])
        new += head

        # Fields and links on one line each, to keep the generated files small.
        parts = []
        for key, label in FIELDS:
            value = need.get(key)
            if value in (None, "", []):
                continue
            if isinstance(value, (list, tuple)):
                children = []
                for i, v in enumerate(value):
                    if i:
                        children.append(nodes.Text(", " if key != "source" else "; "))
                    children.append(nodes.literal(text=str(v)) if key in ("kernel_options", "key") else nodes.Text(str(v)))
            else:
                children = [nodes.Text(str(value))]
            parts.append((label, children))
        link_parts = []
        for key, out_label, in_label in LINKS:
            for field, label in ((key, out_label), (key + "_back", in_label)):
                ids = need.get(field) or []
                if not ids:
                    continue
                children = []
                for i, target in enumerate(_sorted_ids(ids)):
                    if i:
                        children.append(nodes.Text(", "))
                    ref = _need_ref(app, fromdocname, needs, target, titled=field in TITLED)
                    children.extend(ref if isinstance(ref, list) else [ref])
                link_parts.append((label, children))
        for group in (parts, link_parts):
            if not group:
                continue
            para = nodes.paragraph()
            for n, (label, children) in enumerate(group):
                if n:
                    para += nodes.Text(" · ")
                para += nodes.emphasis(text=label + ":")
                para += nodes.Text(" ")
                para.extend(children)
            new += para

        # The body: the directive's content, which sphinx-needs keeps as the
        # Need node's children.
        for child in node.children:
            new += child.deepcopy()
        node.replace_self(new)


def label_ids_first(app, doctree):
    """Put a section's explicit label first among its ids.

    The table of contents links each section by its first id. Docutils makes
    that an id derived from the title, which no anchor in the output carries;
    the explicit label is written as an anchor.
    """
    if app.builder.name != "markdown":
        return
    prefix = posixpath.basename(app.env.docname) + "-"
    for section in doctree.findall(nodes.section):
        ids = section["ids"]
        labelled = [i for i in ids if i.startswith(prefix)]
        if labelled and ids[0] not in labelled:
            section["ids"] = labelled + [i for i in ids if i not in labelled]


def plain_needextend_ids(app, doctree, fromdocname):
    """Sphinx-Needs names the anchor of a needextend after its docname, which has a "/" in a
    subdirectory: make it "-", as the anchors of the other items have no "/"."""
    if app.builder.name != "markdown":
        return
    def plain(i):
        return i.replace("/", "-") if i.startswith("needextend-") else i

    for node in doctree.findall(nodes.Element):
        if node.get("ids"):
            node["ids"] = [plain(i) for i in node["ids"]]
        if node.get("refid"):
            node["refid"] = plain(node["refid"])


def add_headers(app, exception):
    """Start each generated Markdown file with the comment that says it is generated."""
    if exception is not None or app.builder.name != "markdown":
        return
    for docname in app.env.found_docs:
        path = os.path.join(app.outdir, docname + ".md")
        if not os.path.exists(path):
            continue
        with open(path, encoding="utf-8") as f:
            text = f.read()
        header = HEADER.format(docname=docname)
        if not text.startswith(header + "\n"):
            with open(path, "w", encoding="utf-8") as f:
                f.write(header + "\n\n" + text)


def setup(app):
    app.connect("doctree-read", label_ids_first, priority=400)
    app.connect("doctree-resolved", render, priority=400)
    # after Sphinx-Needs has rendered the needextend directives
    app.connect("doctree-resolved", plain_needextend_ids, priority=900)
    app.connect("build-finished", add_headers)
    return {"parallel_read_safe": True, "parallel_write_safe": True}
